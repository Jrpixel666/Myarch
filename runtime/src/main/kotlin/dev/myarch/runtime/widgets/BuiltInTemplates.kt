package dev.myarch.runtime.widgets

/**
 * The templates the builder menu offers.
 *
 * Each one is small enough to read in full and to edit afterwards -- the point
 * is to give someone a working starting place inside the container, not to hide
 * the code behind a generator. The QML targets Quickshell's current API; if a
 * widget stops loading after a Quickshell update, the file is right there in
 * `~/.config/quickshell/myarch/widgets/`.
 */
