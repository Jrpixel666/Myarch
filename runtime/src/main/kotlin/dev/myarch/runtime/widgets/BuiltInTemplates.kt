    private val systemMonitor = BuildTemplate(
        id = "system-monitor",
        title = "System monitor",
        description = "CPU load, memory use and uptime, read straight from /proc.",
        kind = TemplateKind.WIDGET,
        requiredPackages = listOf("qt6-declarative"),
        registerInShell = true,
        notes = "Reads /proc/stat and /proc/meminfo, so it needs no extra tooling. Uses the shared Meter component that ships with the Myarch shell config.",
        files = listOf(
            TemplateFile(
                "$QUICKSHELL_DIR/widgets/{{CLASS}}.qml",
                """
                // {{NAME}} -- generated by the Myarch widget builder.
                import QtQuick
                import QtQuick.Layouts
                import Quickshell.Io
                import "../"

                Rectangle {
                    id: root

                    implicitWidth: 220
                    implicitHeight: 112
                    radius: Theme.radius
                    color: Theme.surface

                    property real cpuPercent: 0
                    property real memoryPercent: 0
                    property int lastIdle: 0
                    property int lastTotal: 0

                    // /proc/stat's first line is cumulative jiffies, so a
                    // percentage needs the delta between two samples.
                    function sampleCpu(text) {
                        const fields = text.split("\n")[0].trim().split(/\s+/).slice(1).map(Number);
                        if (fields.length < 5) return;
                        const idle = fields[3] + fields[4];
                        const total = fields.reduce((a, b) => a + b, 0);
                        const idleDelta = idle - root.lastIdle;
                        const totalDelta = total - root.lastTotal;
                        if (root.lastTotal > 0 && totalDelta > 0) {
                            root.cpuPercent = 100 * (1 - idleDelta / totalDelta);
                        }
                        root.lastIdle = idle;
                        root.lastTotal = total;
                    }

                    function sampleMemory(text) {
                        let total = 0;
                        let available = 0;
                        for (const line of text.split("\n")) {
                            if (line.startsWith("MemTotal:")) total = Number(line.split(/\s+/)[1]);
                            if (line.startsWith("MemAvailable:")) available = Number(line.split(/\s+/)[1]);
                        }
                        if (total > 0) root.memoryPercent = 100 * (1 - available / total);
                    }

                    FileView {
                        id: statFile
                        path: "/proc/stat"
                        onLoaded: root.sampleCpu(text())
                    }

                    FileView {
                        id: memFile
                        path: "/proc/meminfo"
                        onLoaded: root.sampleMemory(text())
                    }

                    Timer {
                        interval: 2000
                        running: true
                        repeat: true
                        triggeredOnStart: true
                        onTriggered: {
                            statFile.reload();
                            memFile.reload();
                        }
                    }

                    ColumnLayout {
                        anchors.fill: parent
                        anchors.margins: Theme.gap
                        spacing: Theme.gap

                        Meter {
                            Layout.fillWidth: true
                            label: "CPU"
                            value: root.cpuPercent
                        }

                        Meter {
                            Layout.fillWidth: true
                            label: "RAM"
                            value: root.memoryPercent
                        }
                    }
                }
                """.trimIndent(),
            ),
        ),
    )

