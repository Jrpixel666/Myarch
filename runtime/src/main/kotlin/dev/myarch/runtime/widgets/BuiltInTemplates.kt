    /** Every template, grouped by kind in the builder menu. */
    public val all: List<BuildTemplate> = listOf(
        clock,
        systemMonitor,
        battery,
        notes,
        weather,
        topBar,
        qmlApplication,
        pythonApplication,
        shellScript,
